from pathlib import Path
from PIL import Image
import json


ROOT = Path(__file__).resolve().parents[1]
SHEETS = ROOT / "asset-audit/contact-sheets"
OUTPUT = ROOT / "miniprogram/packageTaste/assets/foods-temp"
DATA_OUTPUT = ROOT / "miniprogram/packageTaste/data/foods.js"


def load_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def main():
    payload = load_json(ROOT / "data/foods-clean.json")
    unused = load_json(ROOT / "asset-audit/unused-images.json")
    foods = payload["foods"]

    source_names = [
        food["asset"]["filename"]
        for food in foods
        if food["asset"]["status"] != "generated_replacement"
    ]
    source_names.extend(item["filename"] for item in unused)
    source_names = sorted(source_names)
    if len(source_names) != 407 or len(set(source_names)) != 407:
        raise ValueError("Expected 407 unique source image names")

    source_index = {name: index for index, name in enumerate(source_names)}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    mini_foods = []

    for food in foods:
        asset = food["asset"]
        output_name = f'{food["food_code"]}.webp'
        output_path = OUTPUT / output_name

        if asset["status"] == "generated_replacement":
            source = ROOT / asset["project_path"]
            with Image.open(source) as image:
                image = image.convert("RGB")
                image.thumbnail((720, 540), Image.Resampling.LANCZOS)
                image.save(output_path, "WEBP", quality=86, method=6)
            source_kind = "generated_full"
        else:
            index = source_index[asset["filename"]]
            sheet_number = index // 48 + 1
            cell_index = index % 48
            x = (cell_index % 6) * 240
            y = (cell_index // 6) * 205
            with Image.open(SHEETS / f"{sheet_number:02}.jpg") as sheet:
                # The original contact-sheet script fits images inside 232 x 174.
                # Keep the image area only; exclude the filename label underneath.
                crop = sheet.crop((x, y, x + 232, y + 174)).convert("RGB")
                # Keep the prototype package compact. The source cells are already
                # thumbnails, so a smaller WebP preserves all meaningful detail.
                crop = crop.resize((180, 135), Image.Resampling.LANCZOS)
                crop.save(output_path, "WEBP", quality=74, method=6)
            source_kind = "contact_sheet_crop"

        mini_foods.append({
            "food_id": food["food_id"],
            "food_code": food["food_code"],
            "name": food["name"],
            "type": food["type"],
            "color_group_1": food["color_group_1"],
            "color_group_2": food["color_group_2"],
            "intensity": food["intensity"],
            "taste": food["taste"],
            "temperature": food["temperature"],
            "texture": food["texture"],
            "season": food["season"],
            "scene_type": food["scene_type"],
            "ingredient_tags": food["ingredient_tags"],
            "image": f"/packageTaste/assets/foods-temp/{output_name}",
            "asset_source": source_kind,
        })

    DATA_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    js = "// Generated by scripts/build_miniprogram_assets.py\n"
    js += "// Contact-sheet crops are temporary prototype assets, not release assets.\n"
    js += "module.exports = " + json.dumps(mini_foods, ensure_ascii=False, separators=(",", ":")) + ";\n"
    DATA_OUTPUT.write_text(js, encoding="utf-8")
    print(json.dumps({
        "foods": len(mini_foods),
        "contact_sheet_crops": sum(x["asset_source"] == "contact_sheet_crop" for x in mini_foods),
        "generated_full": sum(x["asset_source"] == "generated_full" for x in mini_foods),
        "output": str(OUTPUT.relative_to(ROOT)),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
